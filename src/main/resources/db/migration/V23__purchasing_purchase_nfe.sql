    CONSTRAINT ck_supplier_product_link_factor CHECK (unit_conversion_factor > 0)
);

CREATE INDEX ix_supplier_product_link_product ON purchasing.supplier_product_link (product_id);

-- ---------------------------------------------------------------- histórico de preços (append-only)

CREATE TABLE purchasing.supplier_price_history (
