-- TASK-0021 / I3: compra, documento fiscal (NF-e 55), vínculo de item, parcelas e trilha de auditoria.
--
-- Implementa as decisões aprovadas da DR-0022 (2026-10-13):
--   * D1  custo de aquisição auditável: cada parcela somada fica gravada em purchase_item, não só o total;
--   * D2  rateio proporcional ao valor, com fechamento exato conferido na aplicação (ExpenseAllocation);
--   * D4  obrigações nascem na confirmação da compra, UMA conta a pagar por duplicata, ligadas à compra
--         por purchase_payable, e a soma é conferida contra o total antes de gravar;
--   * D5  mesma chave de acesso não vira duas compras efetivas: índice único PARCIAL, só entre documentos
--         não anulados; a linha anulada permanece no histórico e o hash do XML é sempre gravado;
--   * D6  vínculo "aprendido" por fornecedor + código do fornecedor, nunca por descrição;
--   * D7  fator de conversão gravado no vínculo do item, com as 4 casas da DR-0007;
--   * D9  OWN_TAX_ID com o CNPJ COMPLETO do estabelecimento autorizado; a raiz não vale como prova de
--         identidade e sem ele nenhuma nota confirma;
--   * D11 nota sem duplicata não presume nada: vencimento e parcelas são informados na confirmação.
--
-- Princípios mantidos da V22:
--   * somente aditiva; nada é apagado e nenhuma migration anterior é alterada;
--   * compra e documento nunca são apagados (histórico de estoque, custo e financeiro);
--   * trilha de auditoria e histórico de preços são append-only, recusados pelo banco;
--   * NÃO existe coluna "paga" em compra: a situação financeira é lida do Financeiro, por parcela;
--   * a situação de recebimento é DERIVADA (Σ recebido vs Σ pedido), nunca armazenada.

