-- ---------------------------------------------------------------- compra

CREATE TABLE purchasing.purchase (
    id UUID PRIMARY KEY,
    -- Número sequencial legível da compra, independente do número da nota do fornecedor.
    number BIGINT GENERATED BY DEFAULT AS IDENTITY,
    supplier_id UUID NOT NULL REFERENCES purchasing.supplier(id),
    origin VARCHAR(16) NOT NULL,
    status VARCHAR(24) NOT NULL,
    -- Totais do ciclo comercial, 2 casas porque são valores cobrados (DR-0007).
    goods_total NUMERIC(19,2) NOT NULL,
    discount_total NUMERIC(19,2) NOT NULL DEFAULT 0,
    freight_total NUMERIC(19,2) NOT NULL DEFAULT 0,
    insurance_total NUMERIC(19,2) NOT NULL DEFAULT 0,
    other_total NUMERIC(19,2) NOT NULL DEFAULT 0,
    tax_added_total NUMERIC(19,2) NOT NULL DEFAULT 0,
    payable_total NUMERIC(19,2) NOT NULL,
    -- Categoria de despesa do Financeiro; sem FK, o contrato entre módulos é por id (Spring Modulith).
    expense_category_id UUID,
    -- Condições comerciais do fornecedor no instante da compra, para o histórico não mudar depois.
    commercial_snapshot JSONB,
    work_order_id UUID,
    notes VARCHAR(1000),
    idempotency_key VARCHAR(120) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL,
    created_by UUID NOT NULL,
    cancelled_at TIMESTAMPTZ,
    cancelled_by UUID,
    cancellation_reason VARCHAR(500),
    CONSTRAINT ck_purchase_origin CHECK (origin IN ('NFE_IMPORT', 'DIRECT', 'ORDER')),
    CONSTRAINT ck_purchase_status CHECK (status IN ('DRAFT', 'AWAITING_APPROVAL', 'APPROVED', 'CANCELLED')),
    CONSTRAINT ck_purchase_totals_not_negative CHECK (
        goods_total >= 0 AND discount_total >= 0 AND freight_total >= 0 AND insurance_total >= 0
        AND other_total >= 0 AND tax_added_total >= 0 AND payable_total > 0),
    -- Cancelamento preserva o histórico: motivo obrigatório e coerente com o estado.
    CONSTRAINT ck_purchase_cancelled CHECK (
        (status = 'CANCELLED') = (cancelled_at IS NOT NULL)
        AND (cancelled_at IS NULL OR (cancelled_by IS NOT NULL AND cancellation_reason IS NOT NULL)))
);

CREATE INDEX ix_purchase_supplier ON purchasing.purchase (supplier_id, created_at DESC);
CREATE INDEX ix_purchase_status ON purchasing.purchase (status, created_at DESC);
CREATE INDEX ix_purchase_work_order ON purchasing.purchase (work_order_id) WHERE work_order_id IS NOT NULL;

-- ---------------------------------------------------------------- itens da compra

CREATE TABLE purchasing.purchase_item (
    id UUID PRIMARY KEY,
    purchase_id UUID NOT NULL REFERENCES purchasing.purchase(id),
    line_no INTEGER NOT NULL,
    product_id UUID,
    supplier_code VARCHAR(60),
    description VARCHAR(300) NOT NULL,
    -- Unidade e quantidade ORIGINAIS da nota, preservadas: é o que permite auditar a conversão (D7).
    unit_original VARCHAR(10),
    quantity_original NUMERIC(15,4),
    unit_conversion_factor NUMERIC(19,4) NOT NULL DEFAULT 1,
    -- Quantidade e custo já na unidade do catálogo.
    quantity NUMERIC(15,3) NOT NULL,
    unit_price NUMERIC(19,4) NOT NULL,
    unit_cost NUMERIC(19,4) NOT NULL,
    -- Composição do custo de aquisição gravada parcela por parcela (D1): a conta tem de ser explicável
    -- anos depois sem reabrir o XML, e a soma destas colunas é exatamente acquisition_total.
    cost_base_amount NUMERIC(19,2) NOT NULL,
    cost_ipi_amount NUMERIC(19,2) NOT NULL DEFAULT 0,
    cost_icms_st_amount NUMERIC(19,2) NOT NULL DEFAULT 0,
    cost_icms_normal_amount NUMERIC(19,2) NOT NULL DEFAULT 0,
    cost_freight_share NUMERIC(19,2) NOT NULL DEFAULT 0,
    cost_insurance_share NUMERIC(19,2) NOT NULL DEFAULT 0,
    cost_other_share NUMERIC(19,2) NOT NULL DEFAULT 0,
    acquisition_total NUMERIC(19,2) NOT NULL,
    discount NUMERIC(19,2) NOT NULL DEFAULT 0,
    line_total NUMERIC(19,2) NOT NULL,
    ncm CHAR(8),
    cfop CHAR(4),
    gtin VARCHAR(14),
    work_order_id UUID,
    work_order_item_id UUID,
    CONSTRAINT uq_purchase_item_line UNIQUE (purchase_id, line_no),
    CONSTRAINT ck_purchase_item_quantities CHECK (
        quantity > 0 AND unit_conversion_factor > 0 AND unit_price >= 0 AND unit_cost >= 0
        AND (quantity_original IS NULL OR quantity_original > 0)),
    CONSTRAINT ck_purchase_item_cost_parts CHECK (
        cost_base_amount >= 0 AND cost_ipi_amount >= 0 AND cost_icms_st_amount >= 0
        AND cost_icms_normal_amount >= 0 AND cost_freight_share >= 0 AND cost_insurance_share >= 0
        AND cost_other_share >= 0 AND acquisition_total >= 0),
    -- O banco garante que o total gravado é a soma das parcelas gravadas: sem isso a composição auditável
    -- poderia divergir do total e ninguém notaria.
    CONSTRAINT ck_purchase_item_cost_closes CHECK (
        acquisition_total = cost_base_amount + cost_ipi_amount + cost_icms_st_amount + cost_icms_normal_amount
            + cost_freight_share + cost_insurance_share + cost_other_share)
);

CREATE INDEX ix_purchase_item_purchase ON purchasing.purchase_item (purchase_id, line_no);
CREATE INDEX ix_purchase_item_product ON purchasing.purchase_item (product_id) WHERE product_id IS NOT NULL;

-- ---------------------------------------------------------------- documento fiscal

CREATE TABLE purchasing.purchase_document (
    id UUID PRIMARY KEY,
    purchase_id UUID NOT NULL REFERENCES purchasing.purchase(id),
    kind VARCHAR(16) NOT NULL,
    access_key CHAR(44),
    series VARCHAR(3),
    number BIGINT,
    issued_at TIMESTAMPTZ,
    issuer_document VARCHAR(14),
    recipient_document VARCHAR(14),
    total_amount NUMERIC(19,2),
    protocol_number VARCHAR(20),
    protocol_status VARCHAR(10),
    -- Hash do XML SEMPRE gravado (D5): mesma chave com hash diferente é nota alterada e é bloqueada.
    xml_sha256 CHAR(64),
    xml_content TEXT,
    voided_at TIMESTAMPTZ,
    voided_by UUID,
    void_reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL,
    created_by UUID NOT NULL,
    CONSTRAINT ck_purchase_document_kind CHECK (kind IN ('NFE', 'PROVISIONAL', 'OTHER')),
    -- Chave de acesso existe exatamente quando o documento é NF-e.
    CONSTRAINT ck_purchase_document_access_key CHECK ((kind = 'NFE') = (access_key IS NOT NULL)),
    CONSTRAINT ck_purchase_document_nfe_fields CHECK (
        kind <> 'NFE' OR (xml_sha256 IS NOT NULL AND issuer_document IS NOT NULL AND number IS NOT NULL)),
    CONSTRAINT ck_purchase_document_voided CHECK (
        voided_at IS NULL OR (voided_by IS NOT NULL AND void_reason IS NOT NULL)),
    -- Limite de 2 MB do XML, o mesmo do parser; TEXT sem limite deixaria a nota crescer sem controle.
    CONSTRAINT ck_purchase_document_xml_size CHECK (xml_content IS NULL OR octet_length(xml_content) <= 2097152)
);

-- D5: a MESMA chave de acesso não pode virar duas compras efetivas, mas a nota anulada continua no histórico
-- e a chave volta a poder ser importada. Índice PARCIAL é o que expressa as duas coisas ao mesmo tempo.
CREATE UNIQUE INDEX uq_purchase_document_access_key
    ON purchasing.purchase_document (access_key) WHERE voided_at IS NULL AND access_key IS NOT NULL;

CREATE INDEX ix_purchase_document_purchase ON purchasing.purchase_document (purchase_id);
CREATE INDEX ix_purchase_document_issuer ON purchasing.purchase_document (issuer_document, issued_at DESC);

-- ---------------------------------------------------------------- parcelas ligadas ao Financeiro

CREATE TABLE purchasing.purchase_payable (
    id UUID PRIMARY KEY,
    purchase_id UUID NOT NULL REFERENCES purchasing.purchase(id),
    -- Sem FK para finance.payable: a fronteira entre módulos é por id, não por chave estrangeira
    -- (Spring Modulith). A existência é garantida pelo caso de uso, na mesma transação.
    payable_id UUID NOT NULL UNIQUE,
    installment_no INTEGER NOT NULL,
    due_date DATE NOT NULL,
    amount NUMERIC(19,2) NOT NULL,
    -- Identificação da duplicata na nota, quando a parcela veio dela; nulo quando foi informada (D11).
    invoice_reference VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_purchase_payable_installment UNIQUE (purchase_id, installment_no),
    CONSTRAINT ck_purchase_payable_amount CHECK (amount > 0 AND installment_no >= 1)
);

CREATE INDEX ix_purchase_payable_purchase ON purchasing.purchase_payable (purchase_id, installment_no);

-- ---------------------------------------------------------------- vínculo aprendido de item (D6/D7)

CREATE TABLE purchasing.supplier_product_link (
    id UUID PRIMARY KEY,
    supplier_id UUID NOT NULL REFERENCES purchasing.supplier(id),
    supplier_code VARCHAR(60) NOT NULL,
    gtin VARCHAR(14),
    product_id UUID NOT NULL,
    unit_original VARCHAR(10),
    unit_conversion_factor NUMERIC(19,4) NOT NULL DEFAULT 1,
    confirmed_at TIMESTAMPTZ NOT NULL,
    confirmed_by UUID NOT NULL,
    updated_at TIMESTAMPTZ,
    updated_by UUID,
    -- D6: o vínculo é por fornecedor + código do fornecedor. Nunca por descrição, que erra em silêncio.
