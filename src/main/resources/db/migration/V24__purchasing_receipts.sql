-- DONO e GERENTE_ADMINISTRATIVO recebem as duas; GERENTE_FINANCEIRO continua só com PURCHASE_VIEW. Estornar
-- recebimento reaproveita PURCHASE_CANCEL (V23): é o mesmo poder de desfazer um ato de compra.
INSERT INTO iam.profile_permission (profile_id, permission_id)
SELECT p.id, permission.id
FROM iam.profile p CROSS JOIN iam.permission permission
WHERE p.code IN ('DONO', 'GERENTE_ADMINISTRATIVO')
  AND permission.code IN ('PURCHASE_RECEIVE', 'PURCHASE_DIVERGENCE_ACCEPT')
ON CONFLICT DO NOTHING;
