-- TASK-0021 / I4: recebimento físico, divergência autorizada, entrada em estoque e estorno.
--
-- Implementa as decisões aprovadas da DR-0022 (2026-10-13):
--   * D3  o estoque recebe SOMENTE a quantidade física conferida. Divergência (a mais, ou encerramento do saldo
--         que não virá) exige justificativa E autorização, gravadas junto da linha;
--   * D5  anular/cancelar exige ausência de recebimento ativo: o recebimento é fato imutável e só é desfeito
--         por estorno próprio, nunca por UPDATE nem DELETE;
--   * D1  o custo unitário que o Estoque recebe é o custo de aquisição já gravado no item da compra (I3).
--
-- Princípios mantidos:
--   * somente aditiva; nenhuma migration anterior é alterada;
--   * recebimento, item e estorno são append-only, recusados pelo banco;
--   * a situação de recebimento é DERIVADA (view), nunca armazenada: guardar "recebido" criaria duas verdades;
--   * pedido/importação não movimentam estoque; só o recebimento confirmado chama o contrato do Estoque.

-- ---------------------------------------------------------------- estoque: origem PURCHASE

-- O Estoque continua dono do saldo e do custo médio. Aqui ele só passa a reconhecer a origem "compra" e a
-- guardar de qual item de recebimento veio cada entrada, que é também a chave de idempotência da entrada.
ALTER TABLE inventory.stock_movement DROP CONSTRAINT ck_stock_movement_source;
ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT ck_stock_movement_source CHECK (source_type IN ('MANUAL', 'WORK_ORDER', 'PURCHASE'));

ALTER TABLE inventory.stock_movement ADD COLUMN purchase_receipt_item_id UUID;

-- Origem e referência andam juntas: movimento de compra sempre aponta o item recebido, e só ele.
ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT ck_stock_movement_purchase CHECK ((source_type = 'PURCHASE') = (purchase_receipt_item_id IS NOT NULL));

-- Um item recebido gera no máximo UMA entrada. O estorno (REVERSAL) repete a referência e por isso o índice é
-- parcial por tipo; o estorno único por movimento já é garantido por uq_stock_movement_reversal (V16).
CREATE UNIQUE INDEX uq_stock_movement_purchase_entry
    ON inventory.stock_movement (purchase_receipt_item_id) WHERE movement_type = 'ENTRY';
CREATE INDEX ix_stock_movement_purchase_receipt
    ON inventory.stock_movement (purchase_receipt_item_id) WHERE purchase_receipt_item_id IS NOT NULL;

-- ---------------------------------------------------------------- recebimento

CREATE TABLE purchasing.goods_receipt (
    id UUID PRIMARY KEY,
    -- Número legível do recebimento, independente da compra e da nota.
    number BIGINT GENERATED BY DEFAULT AS IDENTITY,
    purchase_id UUID NOT NULL REFERENCES purchasing.purchase(id),
    -- Documento fiscal ao qual o recebimento se refere, quando houver (AG-05 §§70-73: um recebimento pode
    -- anteceder a nota, e uma nota pode cobrir vários recebimentos).
    document_id UUID REFERENCES purchasing.purchase_document(id),
    received_on DATE NOT NULL,
    notes VARCHAR(1000),
    -- Mesma chave com o mesmo conteúdo devolve o mesmo recebimento; com conteúdo diferente é recusada.
    idempotency_key VARCHAR(120) NOT NULL UNIQUE,
    request_hash CHAR(64) NOT NULL,
    received_by UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX ix_goods_receipt_purchase ON purchasing.goods_receipt (purchase_id, created_at DESC);

CREATE TABLE purchasing.goods_receipt_item (
    id UUID PRIMARY KEY,
    receipt_id UUID NOT NULL REFERENCES purchasing.goods_receipt(id),
    purchase_item_id UUID NOT NULL REFERENCES purchasing.purchase_item(id),
    -- Produto e custo congelados no instante do recebimento: o histórico não muda com o cadastro depois.
    product_id UUID NOT NULL,
    quantity_received NUMERIC(15,3) NOT NULL,
    unit_cost NUMERIC(19,4) NOT NULL,
    -- Saldo pendente da linha ANTES deste recebimento: é o "esperado" contra o qual a divergência é medida.
    expected_quantity NUMERIC(15,3) NOT NULL,
    divergence_type VARCHAR(16) NOT NULL,
    -- Quantidade encerrada sem chegar (fornecedor não enviará o restante). Preserva o que foi pedido, o que
    -- chegou e o que foi cancelado (AG-05 §124), sem reescrever a linha da compra.
    cancelled_quantity NUMERIC(15,3) NOT NULL DEFAULT 0,
    divergence_justification VARCHAR(500),
    divergence_accepted_by UUID,
    -- Movimento do Estoque gerado por este item. Sem FK: a fronteira entre módulos é por id.
    stock_movement_id UUID,
    CONSTRAINT uq_goods_receipt_item_line UNIQUE (receipt_id, purchase_item_id),
    CONSTRAINT ck_goods_receipt_item_values CHECK (
        quantity_received > 0 AND expected_quantity >= 0 AND unit_cost >= 0 AND cancelled_quantity >= 0),
    -- D3: divergência sem aceite e sem justificativa não existe. O banco recusa o que a aplicação deixasse passar.
    CONSTRAINT ck_goods_receipt_item_divergence CHECK (
        (divergence_type = 'NONE'
            AND quantity_received <= expected_quantity AND cancelled_quantity = 0
            AND divergence_justification IS NULL AND divergence_accepted_by IS NULL)
        OR (divergence_type = 'OVER'
            AND quantity_received > expected_quantity AND cancelled_quantity = 0
            AND divergence_accepted_by IS NOT NULL AND btrim(coalesce(divergence_justification, '')) <> '')
        OR (divergence_type = 'SHORT_CLOSED'
            AND quantity_received < expected_quantity AND cancelled_quantity = expected_quantity - quantity_received
            AND divergence_accepted_by IS NOT NULL AND btrim(coalesce(divergence_justification, '')) <> ''))
);

CREATE INDEX ix_goods_receipt_item_purchase_item ON purchasing.goods_receipt_item (purchase_item_id);

-- Estorno total e único do recebimento. O recebimento original permanece intacto.
CREATE TABLE purchasing.goods_receipt_reversal (
    id UUID PRIMARY KEY,
    receipt_id UUID NOT NULL UNIQUE REFERENCES purchasing.goods_receipt(id),
    reason VARCHAR(500) NOT NULL,
    reversed_at TIMESTAMPTZ NOT NULL,
    reversed_by UUID NOT NULL,
    idempotency_key VARCHAR(120) NOT NULL UNIQUE,
    CONSTRAINT ck_goods_receipt_reversal_reason CHECK (btrim(reason) <> '')
);

-- ---------------------------------------------------------------- situação de recebimento DERIVADA

-- Considera só recebimento NÃO estornado. Pendente pode ser negativo: é a marca de recebimento acima do pedido,
-- aceito com justificativa. É a única fonte de "quanto falta", usada pela API, pela lista e pela trava de cancelamento.
CREATE VIEW purchasing.purchase_item_receiving AS
SELECT pi.id AS purchase_item_id,
       pi.purchase_id,
       pi.quantity AS ordered_quantity,
       COALESCE(a.received, 0) AS received_quantity,
       COALESCE(a.closed, 0) AS closed_quantity,
       pi.quantity - COALESCE(a.received, 0) - COALESCE(a.closed, 0) AS pending_quantity
FROM purchasing.purchase_item pi
LEFT JOIN (
    SELECT gi.purchase_item_id,
           SUM(gi.quantity_received) AS received,
           SUM(gi.cancelled_quantity) AS closed
    FROM purchasing.goods_receipt_item gi
    JOIN purchasing.goods_receipt g ON g.id = gi.receipt_id
    WHERE NOT EXISTS (SELECT 1 FROM purchasing.goods_receipt_reversal x WHERE x.receipt_id = g.id)
    GROUP BY gi.purchase_item_id
) a ON a.purchase_item_id = pi.id;

-- ---------------------------------------------------------------- append-only no banco

CREATE TRIGGER tg_goods_receipt_append_only
    BEFORE UPDATE OR DELETE ON purchasing.goods_receipt
    FOR EACH ROW EXECUTE FUNCTION purchasing.forbid_mutation();

CREATE TRIGGER tg_goods_receipt_item_append_only
    BEFORE UPDATE OR DELETE ON purchasing.goods_receipt_item
    FOR EACH ROW EXECUTE FUNCTION purchasing.forbid_mutation();

CREATE TRIGGER tg_goods_receipt_reversal_append_only
    BEFORE UPDATE OR DELETE ON purchasing.goods_receipt_reversal
    FOR EACH ROW EXECUTE FUNCTION purchasing.forbid_mutation();

